export function findPopularCompound(query: string): CompoundDetails | null {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) return null;

  // Direct CID match
  const cidNum = parseInt(trimmed, 10);
  if (!isNaN(cidNum) && String(cidNum) === trimmed) {
    const found = POPULAR_COMPOUNDS.find((c) => c.cid === cidNum);
    if (found) return found;
  }

  // Name or synonym match
  for (const c of POPULAR_COMPOUNDS) {
    if (c.name.toLowerCase() === trimmed) return c;
    if (c.iupacName.toLowerCase() === trimmed) return c;
    if (c.identifiers.canonicalSmiles.toLowerCase() === trimmed) return c;
    if (c.identifiers.inchiKey.toLowerCase() === trimmed) return c;
    if (c.identifiers.casNumber && c.identifiers.casNumber.toLowerCase() === trimmed) return c;
    if (c.identifiers.synonyms.some((s) => s.toLowerCase() === trimmed)) return c;
  }

  // Partial name match
  for (const c of POPULAR_COMPOUNDS) {
    if (c.name.toLowerCase().includes(trimmed) || trimmed.includes(c.name.toLowerCase())) {
      return c;
    }
  }

  return null;
}
