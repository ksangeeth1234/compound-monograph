import { CompoundDetails, LipinskiEvaluation } from '../types';

export function calculateLipinski(props: {
  molecularWeight: number;
  xlogp: number | null;
  hbd: number;
  hba: number;
  rotatableBonds: number;
  tpsa: number;
  heavyAtoms: number;
}): LipinskiEvaluation {
  const mwPass = props.molecularWeight <= 500;
  const logpPass = props.xlogp === null || props.xlogp <= 5.0;
  const hbdPass = props.hbd <= 5;
  const hbaPass = props.hba <= 10;

  let violations = 0;
  if (!mwPass) violations++;
  if (!logpPass) violations++;
  if (!hbdPass) violations++;
  if (!hbaPass) violations++;

  const isStrictPass = violations === 0;
  const isCompliant = violations <= 1;
  const veberPass = props.rotatableBonds <= 10 && props.tpsa <= 140;
  const leadLikenessPass =
    props.molecularWeight <= 350 &&
    (props.xlogp === null || props.xlogp <= 3.0) &&
    props.rotatableBonds <= 7;
  const ghoseFilterPass =
    props.molecularWeight >= 160 &&
    props.molecularWeight <= 480 &&
    (props.xlogp === null || (props.xlogp >= -0.4 && props.xlogp <= 5.6)) &&
    props.heavyAtoms >= 20 &&
    props.heavyAtoms <= 70;

  return {
    mwPass,
    logpPass,
    hbdPass,
    hbaPass,
    violations,
    isCompliant,
    isStrictPass,
    veberPass,
    leadLikenessPass,
    ghoseFilterPass,
  };
}

